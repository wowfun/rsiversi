// Real Session terminal UI, native Bubblewrap shell and bounded independent stream.
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {waitUntil} from './service.mjs';
export async function verifyTerminals(page,service,report,name){
 const stylesBefore=await page.evaluate(()=>document.adoptedStyleSheets.length);
 const panel=page.getByRole('region',{name:'Session terminals'});
 await page.getByRole('button',{name:'Terminal',exact:true}).click();
 await panel.getByRole('button',{name:'New terminal',exact:true}).click();
 await panel.getByRole('status').filter({hasText:'You have control'}).waitFor();
 const typography=await panel.locator('.xterm-rows').evaluate(element=>{const style=getComputedStyle(element);return {family:style.fontFamily,size:style.fontSize,space:style.whiteSpace}});
 assert.match(typography.family,/monospace/,'terminal dynamic CSS did not apply under the product CSP');
 assert.equal(typography.size,'12px');assert.equal(typography.space,'pre');
 async function type(command){await panel.locator('.xterm-helper-textarea').focus();await page.keyboard.type(command);await page.keyboard.press('Enter');}
 await type("printf 'PTY Unicode 界é\\n'; printf 'terminal-ok' > pty-ui-result.txt");
 await waitUntil(async()=>await readFile(join(service.workspace,'pty-ui-result.txt'),'utf8').catch(()=>null)==='terminal-ok','native terminal write');
 await waitUntil(async()=>{const text=await panel.locator('.xterm-rows').innerText();return text.includes('PTY Unicode 界é\n')&&text.includes('terminal-ok')},'drawn Unicode output');
 await waitUntil(async()=>!(await panel.locator('.terminal-footer').innerText()).includes('80 × 24'),'initial native resize');
 await page.screenshot({path:join(report,`${name}-terminal-writer.png`)});
 await type("printf '\\033]0;'; head -c 16384 /dev/zero | tr '\\0' x; printf '\\007AFTER-OSC\\n'");
 await panel.locator('.xterm-rows').filter({hasText:'AFTER-OSC'}).waitFor();
 const palette=()=>page.evaluate(()=>Array.from(document.adoptedStyleSheets).flatMap(sheet=>Array.from(sheet.cssRules)).filter(rule=>rule.selectorText?.includes('.xterm-fg-1')).map(rule=>rule.cssText));
 const paletteBefore=await palette();
 assert(paletteBefore.length>0,'terminal palette fixture must observe the actual renderer CSS');
 await type("stty -echo; printf '\\033[2J\\033[H\\033]0;untrusted-title\\007\\033]8;;https://evil.invalid\\007hidden-link\\033]8;;\\007\\033]4;1;rgb:00/ff/00\\007\\033]10;red\\007\\033]52;c;YXR0YWNr\\007\\033Ppayload\\033\\\\AFTER-SHORT-CONTROLS\\n'");
 await waitUntil(async()=>(await panel.locator('.xterm-rows').innerText()).includes('hidden-linkAFTER-SHORT-CONTROLS'),'actual filtered output after clearing command echo');
 assert.deepEqual(await palette(),paletteBefore,'OSC changed renderer palette CSS');
 assert.equal(await panel.locator('.xterm-rows a').count(),0,'OSC hyperlink reached the renderer');
 assert.equal(await panel.locator('style').count(),0,'terminal installed a style node');
 const wire=await page.evaluate(()=>window.terminalWire);
 assert.equal(wire.blockedReads,12);assert(wire.pages>0);assert.equal(wire.forbidden,0,'OSC/DCS reached the document bridge before xterm parsing');
 await type("export RSI_PTY_MARKER=retained; mkdir -p pty-nested; cd pty-nested; printf ready > ../pty-ready.txt");
 await waitUntil(async()=>await readFile(join(service.workspace,'pty-ready.txt'),'utf8').catch(()=>null)==='ready','persistent shell setup');
 await panel.getByRole('button',{name:'Hide terminal panel'}).click();
 await waitUntil(async()=>await page.evaluate(()=>document.adoptedStyleSheets.length)===stylesBefore,'terminal styles disposed');
 await page.getByRole('button',{name:'Terminal',exact:true}).click();
 await panel.getByRole('button',{name:'Bash 1 · running',exact:true}).click();
 await panel.getByRole('status').filter({hasText:'Read only'}).waitFor();
 await waitUntil(async()=>(await panel.locator('.xterm-rows').innerText()).includes('hidden-linkAFTER-SHORT-CONTROLS'),'reattached snapshot actually rendered');
 await page.screenshot({path:join(report,`${name}-terminal-readonly.png`)});
 const readOnlySize=await panel.locator('.terminal-footer').innerText();
 await page.setViewportSize({width:1000,height:980});
 await panel.getByRole('button',{name:'Take control',exact:true}).click();
 await waitUntil(async()=>(await panel.locator('.terminal-footer').innerText())!==readOnlySize,'takeover applies the current viewport');
 await panel.getByRole('status').filter({hasText:'You have control'}).waitFor();
 await type('printf "%s" "$RSI_PTY_MARKER" > ../pty-retained.txt');
 await waitUntil(async()=>await readFile(join(service.workspace,'pty-retained.txt'),'utf8').catch(()=>null)==='retained','shell environment survived pane detach');
 const wideSize=await panel.locator('.terminal-footer').innerText();
 await page.setViewportSize({width:760,height:900});
 await waitUntil(async()=>{const text=await panel.locator('.terminal-footer').innerText();return text!==wideSize&&/\d+ × \d+/.test(text)},'terminal resized');
 await page.screenshot({path:join(report,`${name}-terminal-narrow.png`)});
 await page.setViewportSize({width:1440,height:980});
 await type('exit 7');
 await panel.getByRole('status').filter({hasText:'Exited 7'}).waitFor();
 await page.screenshot({path:join(report,`${name}-terminal-exited.png`)});
 await panel.getByRole('button',{name:'Close terminal',exact:true}).click();
 await panel.locator('.terminal-empty').waitFor();
 await waitUntil(async()=>await panel.locator('.terminal-tabs button').count()===0,'terminal roster refreshed after close');
 await panel.getByRole('button',{name:'Hide terminal panel'}).click();
 await writeFile(join(report,`${name}-terminal.json`),JSON.stringify({native_shell:true,unicode:true,admission_backpressure_recovered:true,takeover_resized:true,bridge_controls_filtered:true,oversized_osc_filtered:true,short_application_controls_filtered:true,readonly_reattach:true,explicit_takeover:true,shell_environment_retained:true,resize:true,exit_code:7,explicit_close:true},null,2));
}
