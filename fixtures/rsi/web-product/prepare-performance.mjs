import {readFile,writeFile,mkdir,cp,symlink} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
const [baseline,directory]=process.argv.slice(2).map(path=>resolve(path));
if(!baseline||!directory) throw new Error('Pass baseline assets and a new absolute output directory');
await mkdir(directory,{recursive:false});
const root=resolve('plugins/rsi/web'), scene=await readFile('fixtures/rsi/web-product/performance-scene.js','utf8');
await cp(baseline,join(directory,'baseline'),{recursive:true});
const old=await readFile(join(baseline,'app.js'),'utf8');
await writeFile(join(directory,'baseline/app.js'),old+'\n'+scene);
const source=join(directory,'source');
await cp(root,source,{recursive:true,filter:path=>!path.split('/').includes('node_modules')});
await symlink(join(root,'node_modules'),join(source,'node_modules'),'dir');
let app=await readFile(join(source,'app.js'),'utf8');
app=app.replace('export function initialize() {','export async function initialize() {');
const start=app.lastIndexOf('if (location.protocol === "rsi:") {');
if(start<0) throw new Error('Native bootstrap marker changed; review instrumentation');
app=app.slice(0,start)+scene+'\n}\n';
await writeFile(join(source,'app.js'),app);
const {build}=await import(join(root,'node_modules/vite/dist/node/index.js'));
await cp(process.env.RSI_WEB_ASSETS,join(directory,'current'),{recursive:true});
await build({root:source,configFile:join(source,'vite.config.mjs'),build:{outDir:join(directory,'current')}});
await writeFile(join(directory,'instrumentation.json'),JSON.stringify({baseline_app_sha256:createHash('sha256').update(old).digest('hex'),current_source_app_sha256:createHash('sha256').update(await readFile(join(root,'app.js'))).digest('hex'),scene_sha256:createHash('sha256').update(scene).digest('hex'),boundary:'Document projections and persistence in the same production Tauri/Host; no live transport/provider measurement'},null,2));
