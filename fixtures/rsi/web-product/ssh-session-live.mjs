// Explicitly invoked by the SSH product fixture after Local trust and Device Use.
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {waitUntil} from './service.mjs';
import {detailMode,resources} from './controls.mjs';
export async function verifySshSession({page,service,report,dialog,target,checks}) {
  const workspace=join(service.workspace,'picked-on-target');
  const marker=`SSH_PROJECT_${target.candidate.target}`;
  execFileSync('git',['init','--quiet',service.workspace]);
  const ancestorMarker=`SSH_ANCESTOR_${target.candidate.target}`;
  await writeFile(join(service.workspace,'AGENTS.md'),`Include the exact ancestor marker ${ancestorMarker} in your final reply.\n`);
  await writeFile(join(workspace,'AGENTS.md'),`For this isolated verification, include the exact project marker ${marker} in your final reply.\n`);
  await writeFile(join(workspace,'card.txt'),'before\n');
  await dialog.getByRole('button',{name:'Open',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await detailMode(page,'verbose');
  const pane=page.getByRole('region',{name:'Main conversation',exact:true});
  await pane.getByRole('textbox',{name:'Main message',exact:true}).fill('Verify this isolated SSH workspace. First use bash once to write exactly ssh-bash-ok to ssh-bash.txt and print the working directory. Then use apply_patch once with exactly this patch string: *** Begin Patch\n*** Update File: card.txt\n@@\n-before\n+after-ssh\n*** End Patch\n. You may read the file first. In your final answer include both project instruction markers and SSH_SESSION_DONE.');
  await pane.getByTestId('composer-send').click();
  await waitUntil(async()=>{
    const review=pane.locator('.pending button').filter({hasText:'Review:'});
    if(await review.count()&&await review.first().isVisible()){
      await review.first().click();await page.getByRole('button',{name:'Allow once',exact:true}).click();
    }
    return (await pane.locator('.pane-status').innerText()).includes('Completed');
  },'real DeepSeek SSH tools and settlement',180000);
  const session=(await pane.locator('.pane-session').innerText()).split(' · ').at(-1);
  const records=service.run(['--profile','evidence-cli','--resume',session,'--output','jsonl'],{input:':history\n'.repeat(8)+':exit\n'}).stdout.trim().split('\n').map(line=>JSON.parse(line));
  const facts=records.flatMap(record=>record.fact?[record.fact]:[]).sort((a,b)=>a.seq-b.seq);
  await writeFile(join(report,'ssh-session-facts.json'),JSON.stringify(facts,null,2));
  const transcript=await pane.locator('.transcript').innerText();
  await writeFile(join(report,'ssh-session-transcript.txt'),transcript);
  assert.match(transcript,/SSH_SESSION_DONE/);assert(transcript.includes(marker),transcript);assert(transcript.includes(ancestorMarker),transcript);
  assert.equal(await readFile(join(workspace,'ssh-bash.txt'),'utf8'),'ssh-bash-ok');
  assert.equal(await readFile(join(workspace,'card.txt'),'utf8'),'after-ssh\n');
  assert.equal(service.provider.requests.length,0,'no mock model requests');
  const tools=facts.filter(fact=>fact.type==='tool_result');
  const intents=facts.filter(fact=>fact.type==='tool_intent');
  assert(intents.some(fact=>fact.name==='bash'));
  assert.equal(intents.filter(fact=>fact.name==='bash' && />\s*ssh-bash\.txt/.test(fact.arguments.command)).length,1,'one explicit target file write');
  assert.equal(intents.filter(fact=>fact.name==='apply_patch').length,1);
  assert.equal(tools.length,intents.length);assert(tools.every(fact=>!fact.result.is_error));
  assert.equal(new Set(tools.map(fact=>fact.effect_id)).size,tools.length,'each accepted effect settles once');
  checks.push('actual SSH Session with DeepSeek, target AGENTS marker, Bash and apply_patch settled once');
  await resources(page);
  await page.getByRole('button',{name:'Workspace files',exact:true}).click();
  const content=page.locator('.resource-content .ui-contribution:visible');
  await content.getByRole('textbox',{name:'Workspace-relative path',exact:true}).fill('card.txt');
  await content.getByRole('button',{name:'Read file',exact:true}).click();
  await content.locator('pre').filter({hasText:'after-ssh'}).waitFor();
  await page.screenshot({path:join(report,'ssh-session-files.png')});
  await page.getByRole('button',{name:'Open resources',exact:true}).first().click();
  await page.getByRole('button',{name:'Workspace changes',exact:true}).click();
  await content.getByRole('button',{name:'Review workspace changes',exact:true}).click();
  await content.getByRole('button',{name:'Open interval files',exact:true}).first().click();
  await content.getByRole('button',{name:'Open file diff',exact:true}).first().click();
  await content.locator('pre').waitFor();
  assert.match(await content.locator('pre').innerText(),/after-ssh|ssh-bash-ok/);
  await page.screenshot({path:join(report,'ssh-session-review.png')});
  await page.getByRole('button',{name:'Open resources',exact:true}).first().click();
  checks.push('SSH Session Files and Review render target bytes and settled diff');
  const options=page.locator('.conversation-menu');if(!await options.evaluate(node=>node.open))await options.locator('summary').click();
  await page.getByRole('button',{name:'Terminal',exact:true}).click();await options.locator('summary').click();
  await page.getByRole('button',{name:'New terminal',exact:true}).click();
  const terminal=page.getByRole('region',{name:'Session terminals'});
  await terminal.getByRole('status').filter({hasText:'You have control'}).waitFor();
  await terminal.locator('.xterm-helper-textarea').focus();
  await page.keyboard.type("printf 'ssh-pty-ok' > ssh-pty.txt; printf 'SSH_PTY_VISIBLE\\n'");await page.keyboard.press('Enter');
  await waitUntil(async()=>await readFile(join(workspace,'ssh-pty.txt'),'utf8').catch(()=>null)==='ssh-pty-ok','actual SSH PTY write');
  await terminal.locator('.xterm-rows').filter({hasText:'SSH_PTY_VISIBLE'}).waitFor();
  await page.screenshot({path:join(report,'ssh-session-terminal.png')});
  await terminal.locator('.xterm-helper-textarea').focus();await page.keyboard.type('exit 0');await page.keyboard.press('Enter');
  await terminal.getByRole('status').filter({hasText:'Exited 0'}).waitFor();
  await terminal.getByRole('button',{name:'Terminate terminal',exact:true}).click();
  await terminal.getByRole('button',{name:'Hide terminal panel',exact:true}).click();
  checks.push('SSH terminal through Session API accepts input, renders output and reports actual exit');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Plugins',exact:true}).click();
  return session;
}
