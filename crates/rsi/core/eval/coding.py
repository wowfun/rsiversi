def durable_trace(root):
    database = root / "state/rsi/agent/sessions.sqlite3"
    if not database.exists():
        return {"facts": [], "controls": []}
    trace = {"facts": [], "controls": []}
    try:
        with sqlite3.connect(f"file:{database}?mode=ro", uri=True) as connection:
            trace["facts"] = [json.loads(row[0]) for row in connection.execute("SELECT fact_json FROM facts ORDER BY session_id,seq")]
            trace["controls"] = [json.loads(row[0]) for row in connection.execute("SELECT control_json FROM agent_controls ORDER BY session_id,seq")]
    except (sqlite3.Error, ValueError) as error:
        trace["read_error"] = str(error)
    return trace


def record_trace_summary(report, trace):
    report.update({"provider_attempts": 0, "tool_calls": 0, "actual_model_snapshots": [], "usage": [], "terminals": []})
    try:
        facts = trace["facts"]
        if not isinstance(facts, list):
            raise ValueError("Facts must be an array")
        for fact in facts:
            kind = fact["type"]
            if kind == "model_started":
                report["provider_attempts"] += 1
            elif kind == "tool_started":
                report["tool_calls"] += 1
            elif kind == "model_intent":
                snapshot = fact["snapshot"]
                if not isinstance(snapshot, dict):
                    raise ValueError("model snapshot must be an object")
                report["actual_model_snapshots"].append(snapshot)
            elif kind == "model_event" and fact["event"]["type"] == "usage":
                usage = fact["event"]["usage"]
                if not isinstance(usage, dict):
                    raise ValueError("usage must be an object")
                report["usage"].append(usage)
            elif kind == "turn_terminal":
                outcome = fact["outcome"]
                if not isinstance(outcome, dict) or not isinstance(outcome["status"], str):
                    raise ValueError("terminal outcome must have a status")
                report["terminals"].append(outcome)
        terminals = report["terminals"]
        if any(outcome["status"] == "budget_exceeded" for outcome in terminals):
            if report.get("classification") != "infrastructure_failure":
                report["classification"] = "budget_exhausted"
            report["budget_source"] = "turn_budget"
        if "read_error" in trace or not report["actual_model_snapshots"]:
            report["classification"] = "infrastructure_failure"
        if any(outcome.get("code") == "tool.execution" and "helper exited unexpectedly" in outcome.get("message", "") for outcome in terminals):
            report["classification"] = "infrastructure_failure"
    except (KeyError, TypeError, ValueError) as error:
        report["classification"] = "infrastructure_failure"
        report["trace_projection_error"] = f"{type(error).__name__}: {error}"[:4096]
    report.setdefault("classification", "passed")


def live(args):
    key = read_key(args.key_file)
    binary = args.binary.resolve()
    if not binary.is_file():
        raise ValueError("build the rsi binary before live evaluation")
    if binary.is_relative_to(Path(tempfile.gettempdir())):
        raise ValueError("the rsi executable must be outside private sandbox /tmp so its patch helper remains executable")
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    results = []
    binary_sha256 = hashlib.sha256(binary.read_bytes()).hexdigest()
    for task in TASKS:
        if args.task and task["id"] not in args.task:
            continue
        report = {"task": task["id"], "task_version": TASK_VERSION, "requested_model": args.model, "binary_sha256": binary_sha256,
                  "limits": {"task_wall_seconds": 480, "turn_execution_ms": 480000, "provider_attempts": PROVIDER_ATTEMPTS_PER_TURN * len(task["prompts"]), "tool_calls": 48, "task_attempts": 1, "agent_stream_bytes": MAXIMUM_AGENT_OUTPUT_BYTES}, "stages": []}
        started = time.monotonic()
        destination = output / task["id"]
        destination.mkdir()
        with tempfile.TemporaryDirectory(prefix="rsi-live-coding-") as temporary:
            root = Path(temporary)
            workspace = root / "workspace"
            write_project(workspace, task["initial"])
            report["settings"] = configure(root, args.model, len(task["prompts"]))
            env = clean_environment()
            env.update({"XDG_CONFIG_HOME": str(root / "config"), "XDG_STATE_HOME": str(root / "state"), "XDG_CACHE_HOME": str(root / "cache"),
                        "XDG_RUNTIME_DIR": str(root / "runtime"), "DEEPSEEK_API_KEY": key})
            (root / "runtime").mkdir(mode=0o700)
            initial_oracle = oracle(workspace, task, 0)
            report["initial_oracle"] = initial_oracle
            if initial_oracle["passed"]:
                raise ValueError("initial task unexpectedly passes its oracle")
            if "infrastructure_error" in initial_oracle:
                report["classification"] = "infrastructure_failure"
            else:
                try:
                    probe_command = agent_command(binary, root, env, [])
                    probe_command[-1] = "/usr/bin/true"
                    probe = run_oracle_process(probe_command, env, 5)
                except OSError as error:
                    probe = {"exit_code": None, "launch_error": str(error)}
                report["agent_preflight"] = probe
                if probe["exit_code"] != 0:
                    report["classification"] = "infrastructure_failure"
            for stage, prompt in enumerate(task["prompts"]):
                if report.get("classification") == "infrastructure_failure":
                    break
                remaining = 480 - (time.monotonic() - started)
                if remaining <= 0:
                    report["classification"] = "budget_exhausted"
                    report["budget_source"] = "task_wall_deadline"
                    break
                arguments = ["--profile", "live", prompt, "--cwd", str(workspace), "--output", "jsonl",
                             "--session-id" if stage == 0 else "--resume", "coding-session"]
                try:
                    command = agent_command(binary, root, env, arguments)
                except OSError as error:
                    report["classification"] = "infrastructure_failure"
                    report["agent_launch_error"] = str(error)
                    break
                execution = run_oracle_process(command, env, remaining, maximum_output_bytes=MAXIMUM_AGENT_OUTPUT_BYTES)
                stdout, stderr = execution["stdout"].encode(), execution["stderr"].encode()
                timed_out = execution["timed_out"]
                # Secret values never become report or trace data, even on an
                # unexpected dependency failure.
                if key.encode() in stdout or key.encode() in stderr:
                    raise ValueError("credential appeared in child output; refusing to persist it")
                (destination / f"stage-{stage+1}.jsonl").write_bytes(stdout)
                (destination / f"stage-{stage+1}.stderr").write_bytes(stderr)
                checked = oracle(workspace, task, stage)
                report["stages"].append({**{name: value for name, value in execution.items() if name not in ("stdout", "stderr")}, "oracle": checked})
                if "launch_error" in execution or execution.get("output_limit_exceeded"):
                    report["classification"] = "infrastructure_failure"
                    break
                if timed_out:
                    report["classification"] = "budget_exhausted"
                    report["budget_source"] = "task_wall_deadline"
                    break
                if "infrastructure_error" in checked:
                    report["classification"] = "infrastructure_failure"
                    break
                if execution["exit_code"] != 0 or not checked["passed"]:
                    report["classification"] = "agent_failure" if execution["exit_code"] else "behavioral_failure"
                    break
            # Preserve bounded allowlisted source evidence even when admission
            # rejects a Cargo-file mutation; grading remains external.
            evidence = {}
            for name in [*task["initial"], "Cargo.toml", "Cargo.lock"]:
                path = workspace / name
                if path.is_file() and not any(parent.is_symlink() for parent in [path, *path.parents]) and path.stat().st_size <= 65536:
                    value = path.read_text()
                    if key in value:
                        raise ValueError("credential appeared in source evidence; refusing to persist it")
                    evidence[name] = value
            (destination / "source-evidence.json").write_text(json.dumps(evidence, indent=2))
            trace = durable_trace(root)
            record_trace_summary(report, trace)
            try:
                sources = safe_sources(workspace, task)
                diff = "".join("".join(difflib.unified_diff(task["initial"][name].splitlines(True), text.splitlines(True), fromfile="a/"+name, tofile="b/"+name)) for name, text in sources.items())
                (destination / "source.diff").write_text(diff)
                write_project(destination / "result", sources)
            except (ValueError, OSError) as error:
                report["source_admission_error"] = str(error)
                if report["classification"] == "passed":
                    report["classification"] = "behavioral_failure"
            trace_text = json.dumps(trace, indent=2)
            if key in trace_text:
                raise ValueError("credential appeared in durable trace; refusing to persist it")
            (destination / "durable-trace.json").write_text(trace_text)
            report["elapsed_seconds"] = round(time.monotonic() - started, 3)
        (destination / "report.json").write_text(json.dumps(report, indent=2))
        results.append(report)
        print(json.dumps({"task": task["id"], "classification": report["classification"], "elapsed_seconds": report["elapsed_seconds"], "provider_attempts": report["provider_attempts"], "tool_calls": report["tool_calls"]}), flush=True)
    (output / "results.json").write_text(json.dumps(results, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--self-test", action="store_true")
    action.add_argument("--live", action="store_true")
    parser.add_argument("--key-file", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--task", action="append", choices=[task["id"] for task in TASKS])
    parser.add_argument("--model", default="deepseek-v4-flash")
    parser.add_argument("--binary", type=Path, default=ROOT / "target/debug/rsi")
    args = parser.parse_args()
    if args.self_test:
        self_test()
    else:
        if args.key_file is None or args.output is None:
            parser.error("--live requires --key-file and --output")
        if not re.fullmatch(r"[A-Za-z0-9_-]+", args.model):
            parser.error("model must be one exact identifier")
        live(args)


if __name__ == "__main__":
    main()
