def self_test_timeouts():
    """Exercise real Rust descendants and the opt-in report writer without a service."""
    import sys
    from types import SimpleNamespace
    from unittest.mock import patch

    if not sys.platform.startswith("linux"):
        raise RuntimeError("timeout containment self-tests require Linux /proc")
    with tempfile.TemporaryDirectory(prefix="rsi-eval-timeout-") as temporary:
        root = Path(temporary)
        payload = ('pub fn truncate_utf8(_: &str, _: usize) -> &str { '
                   'std::process::Command::new("/usr/bin/setsid").args(["/bin/sleep", "30"]).spawn().unwrap(); '
                   'eprintln!("timeout fixture started"); '
                   'loop { std::thread::sleep(std::time::Duration::from_millis(10)); } }')
        observed = {}
        observers = []
        observation_stop = threading.Event()
        popen = subprocess.Popen

        def process_identity(pid):
            try:
                stat_text = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()
                return stat_text[19], stat_text[0]
            except (FileNotFoundError, ProcessLookupError):
                return None

        def observe_subtree(pid):
            while not observation_stop.is_set():
                pending = [pid]
                seen = set()
                while pending:
                    current = pending.pop()
                    if current in seen:
                        continue
                    seen.add(current)
                    identity = process_identity(current)
                    if identity is None:
                        continue
                    try:
                        name = Path(f"/proc/{current}/comm").read_text().strip()
                        children = Path(f"/proc/{current}/task/{current}/children").read_text()
                    except (FileNotFoundError, ProcessLookupError):
                        continue
                    observed[current] = (identity[0], name)
                    pending.extend(int(child) for child in children.split())
                observation_stop.wait(0.005)

        def observed_popen(command, **kwargs):
            process = popen(command, **kwargs)
            if Path(command[0]).name == "bwrap":
                thread = threading.Thread(target=observe_subtree, args=(process.pid,), daemon=True)
                thread.start()
                observers.append(thread)
            return process

        def finish_observation():
            observation_stop.set()
            for thread in observers:
                thread.join(timeout=1)
                assert not thread.is_alive(), "subtree observer did not finish"

        def assert_stopped():
            finish_observation()
            assert any(name == "sleep" for _, name in observed.values()), "fixture descendant was never observed"
            for pid, (start, _) in observed.items():
                identity = process_identity(pid)
                assert identity is None or identity[0] != start or identity[1] == "Z", f"oracle descendant {pid} still runs"

        try:
            workspace = root / "workspace"
            write_project(workspace, {"src/lib.rs": payload})
            with patch.object(subprocess, "Popen", side_effect=observed_popen):
                result = oracle(workspace, TASKS[0], 0, timeout_seconds=3)
            assert result["timed_out"] and not result["passed"] and result["phase"] == "execute", result
            assert not result["checks_completed"]
            assert_stopped()
            observed.clear()
            observers.clear()
            observation_stop.clear()

            # Only the Agent binary and durable model evidence are fixtures here;
            # source grading, process supervision, and report persistence stay real.
            key_file = root / "fixture.env"
            key_file.write_text("DEEPSEEK_API_KEY=offline-key-not-a-real-credential\n")
            output = root / "reports"
            args = SimpleNamespace(key_file=key_file, binary=Path(sys.executable), output=output,
                                   task=["utf8-truncate"], model="offline-fixture")
            grade = oracle

            def fixture_agent(command, **kwargs):
                if "--profile" in command:
                    workspace = Path(command[command.index("--cwd") + 1])
                    program = f"from pathlib import Path; Path({str(workspace / 'src/lib.rs')!r}).write_text({payload!r})"
                    return popen([sys.executable, "-c", program], **kwargs)
                return observed_popen(command, **kwargs)

            trace = {"facts": [{"type": "model_intent", "snapshot": {"model": "offline-fixture"}}], "controls": []}
            with patch.object(subprocess, "Popen", side_effect=fixture_agent), \
                    patch(__name__ + ".oracle", side_effect=lambda workspace, task, stage: grade(workspace, task, stage, timeout_seconds=3)), \
                    patch(__name__ + ".durable_trace", return_value=trace):
                live(args)
            report = json.loads((output / "utf8-truncate/report.json").read_text())
            assert report["classification"] == "behavioral_failure", report
            assert report["stages"][0]["oracle"]["timed_out"]
            assert (output / "utf8-truncate/source-evidence.json").is_file()
            assert (output / "utf8-truncate/durable-trace.json").is_file()
            assert json.loads((output / "results.json").read_text())[0] == report
            assert_stopped()
        finally:
            finish_observation()
            for pid, (start, _) in observed.items():
                identity = process_identity(pid)
                if identity and identity[0] == start and identity[1] != "Z":
                    try:
                        os.kill(pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
