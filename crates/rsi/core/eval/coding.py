def oracle_namespace():
    bubblewrap = shutil.which("bwrap")
    if not bubblewrap:
        raise OSError("Linux Bubblewrap is required for isolated oracle execution")
    command = [bubblewrap, "--unshare-all", "--unshare-user", "--disable-userns", "--die-with-parent", "--new-session", "--cap-drop", "ALL", "--clearenv", "--setenv", "LANG", "C.UTF-8"]
    for directory in ["/usr", "/bin", "/lib", "/lib64"]:
        if Path(directory).exists():
            command.extend(["--ro-bind", directory, directory])
    if Path("/etc/ld.so.cache").exists():
        command.extend(["--ro-bind", "/etc/ld.so.cache", "/etc/ld.so.cache"])
    command.extend(["--proc", "/proc", "--dev", "/dev", "--tmpfs", "/tmp"])
    return command


def oracle_sandbox(binary):
    command = oracle_namespace()
    command.extend(["--dir", "/work", "--ro-bind", str(binary), "/work/runner", "--chdir", "/work", "--", "/work/runner"])
    return command


def oracle_compile_command(root, env):
    cargo = shutil.which("cargo")
    if not cargo:
        raise OSError("Cargo is unavailable")
    command = oracle_namespace()
    for directory in [str(Path(cargo).parent), env["RUSTUP_HOME"], "/etc/alternatives"]:
        if Path(directory).exists():
            command.extend(["--ro-bind", directory, directory])
    # Keeping the project at its original absolute path also keeps artifact paths
    # usable by the parent. Ancestor directories are empty namespace scaffolding.
    command.extend(["--bind", str(root), str(root), "--chdir", str(root)])
    for name, value in env.items():
        command.extend(["--setenv", name, value])
    command.extend(["--", cargo, "test", "--no-run", "--test", "oracle", "--message-format=json",
                    "--offline", "--locked", "--manifest-path", str(root / "Cargo.toml")])
    return command


def agent_command(binary, root, env, arguments):
    command = oracle_namespace()
    # Tools need to create their own restricted user/PID namespaces. The
    # provider key stays in env, never in --setenv argv or a mounted key file.
    command.remove("--disable-userns")
    command.remove("--clearenv")
    command.extend(["--share-net"])
    cargo = shutil.which("cargo")
    if not cargo:
        raise OSError("Cargo is unavailable")
    env["RUSTUP_HOME"] = env.get("RUSTUP_HOME", str(Path.home() / ".rustup"))
    for directory in [str(Path(cargo).parent), env["RUSTUP_HOME"], "/etc/alternatives", "/etc/ssl"]:
        if Path(directory).exists():
            command.extend(["--ro-bind", directory, directory])
    for name in ["/etc/resolv.conf", "/etc/hosts", "/etc/nsswitch.conf"]:
        if Path(name).exists():
            command.extend(["--ro-bind", name, name])
    for name, directory in [("HOME", "home"), ("CARGO_HOME", "cargo-home")]:
        private = root / directory
        private.mkdir(exist_ok=True)
        env[name] = str(private)
    env["PATH"] = f"{Path(cargo).parent}:/usr/local/bin:/usr/bin:/bin"
    command.extend(["--bind", str(root), str(root), "--ro-bind", str(binary), "/opt/rsi-eval/rsi",
                    "--chdir", str(root / "workspace"), "--", "/opt/rsi-eval/rsi", *arguments])
    return command


def oracle(workspace, task, stage, timeout_seconds=30):
    try:
        sources = safe_sources(workspace, task)
    except (ValueError, OSError) as error:
        return {"passed": False, "admission_error": str(error)}
    cases = oracle_cases(task["id"], stage)
    manifest = MANIFEST + '\n[[test]]\nname = "oracle"\nharness = false\n'
    driver = oracle_runner(task["id"])
    oracle_hash = hashlib.sha256((manifest + LOCK + driver + json.dumps(cases)).encode()).hexdigest()
    report = {"passed": False, "checks_completed": False, "checks": len(cases), "phase": "sandbox",
              "timeout_seconds": timeout_seconds, "oracle_sha256": oracle_hash}
    deadline = time.monotonic() + timeout_seconds
    try:
        probe_command = oracle_sandbox(Path("/usr/bin/true"))
    except OSError as error:
        return {**report, "infrastructure_error": str(error)}
    runtime_env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin")}
    probe = run_oracle_process(probe_command, runtime_env, min(5, deadline - time.monotonic()))
    if probe["exit_code"] != 0 or probe["timed_out"]:
        return {**report, **probe, "infrastructure_error": "Bubblewrap isolation preflight failed"}
    with tempfile.TemporaryDirectory(prefix="rsi-oracle-") as temporary:
        root = Path(temporary)
        write_project(root, sources)
        (root / "Cargo.toml").write_text(manifest)
        (root / "tests").mkdir()
        (root / "tests/oracle.rs").write_text(driver)
        env = clean_environment()
        env["RUSTUP_HOME"] = env.get("RUSTUP_HOME", str(Path.home() / ".rustup"))
        for name, directory in [("HOME", "home"), ("CARGO_HOME", "cargo-home"), ("CARGO_TARGET_DIR", "target")]:
            (root / directory).mkdir()
            env[name] = str(root / directory)
        try:
            compile_command = oracle_compile_command(root, env)
        except OSError as error:
            return {**report, "phase": "compile", "infrastructure_error": str(error)}
        build = run_oracle_process(compile_command,
                                   env, deadline - time.monotonic(), cwd=root)
        report.update({**build, "phase": "compile"})
        if "launch_error" in build:
            return {**report, "infrastructure_error": "oracle compiler could not start"}
        if build["exit_code"] != 0 or build["timed_out"] or build["output_limit_exceeded"]:
            return report
        artifacts = []
        for line in build["stdout"].splitlines():
            try:
                message = json.loads(line)
            except ValueError:
                continue
            if message.get("reason") == "compiler-artifact" and message.get("target", {}).get("name") == "oracle" and message.get("executable"):
                artifacts.append(message["executable"])
        if len(artifacts) != 1:
            return {**report, "infrastructure_error": "expected exactly one external oracle executable"}
        result = run_oracle_process(oracle_sandbox(Path(artifacts[0])), runtime_env, deadline - time.monotonic(),
                                    input_bytes="".join(source + "\n" for source, _ in cases).encode())
        report.update({**result, "phase": "execute", "build": build, "isolation": "bubblewrap"})
        if "launch_error" in result:
            return {**report, "infrastructure_error": "oracle sandbox could not start"}
        expected = [expected for _, expected in cases]
        observed = result["stdout"].splitlines()
        completed = result["exit_code"] == 0 and not result["timed_out"] and not result["output_limit_exceeded"] and len(observed) == len(expected)
        report["checks_completed"] = completed
        report["passed"] = completed and observed == expected
        if not report["passed"]:
            report["mismatches"] = [{"case": index, "expected": want, "observed": observed[index] if index < len(observed) else None}
                                    for index, want in enumerate(expected) if index >= len(observed) or observed[index] != want][:4]
        return report


def self_test():
    checks = 0
    for task in TASKS:
        with tempfile.TemporaryDirectory(prefix="rsi-eval-fixture-") as temporary:
            workspace = Path(temporary)
            for stage in range(len(task["prompts"])):
                before = task["initial"] if stage == 0 else task["reference"][stage - 1]
                write_project(workspace, before)
                assert not oracle(workspace, task, stage)["passed"], (task["id"], "initial oracle must fail")
                write_project(workspace, task["reference"][stage])
