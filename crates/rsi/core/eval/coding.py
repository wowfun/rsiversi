def write_project(root, sources):
    root.mkdir(parents=True, exist_ok=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    for name, text in sources.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def module_declarations(source):
    # This fixed-layout file permits only declarations after comments disappear;
    # literals/attributes left over still fail the exact declaration allowlist.
    visible = []
    cursor = 0
    while cursor < len(source):
        if source.startswith("//", cursor):
            end = source.find("\n", cursor)
            cursor = len(source) if end < 0 else end
        elif source.startswith("/*", cursor):
            cursor += 2
            depth = 1
            while depth and cursor < len(source):
                if source.startswith("/*", cursor):
                    depth += 1
                    cursor += 2
                elif source.startswith("*/", cursor):
                    depth -= 1
                    cursor += 2
                else:
                    cursor += 1
            if depth:
                raise ValueError("unterminated module-layout comment")
            visible.append(" ")
        else:
            visible.append(source[cursor])
            cursor += 1
    source = "".join(visible)
    return sorted(re.sub(r"\s+", "", source).split(";"))


def safe_sources(workspace, task):
    for name, expected in [("Cargo.toml", MANIFEST), ("Cargo.lock", LOCK)]:
        path = workspace / name
        if path.is_symlink() or not path.is_file() or path.read_text() != expected:
            raise ValueError(f"fixed {name} changed")
    if (workspace / ".cargo").exists() or (workspace / "build.rs").exists():
        raise ValueError("Cargo configuration or build script is forbidden")
    allowed = set(task["initial"])
    actual = {str(path.relative_to(workspace)) for path in (workspace / "src").rglob("*.rs")}
    if actual != allowed:
        raise ValueError("source module allowlist changed")
    sources = {}
    for name in sorted(allowed):
        path = workspace / name
        if any(parent.is_symlink() for parent in [path, *path.parents] if parent != workspace.parent):
            raise ValueError("source symlink is forbidden")
        metadata = path.stat()
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1 or metadata.st_size > 65536:
            raise ValueError("source is not one bounded regular file")
        text = path.read_text()
        # These fixed tasks use a conservative lexical subset, not arbitrary
        # Rust. Reject the macro names even when imported under another name.
        if re.search(r"\b(?:include|include_str|include_bytes|cfg|cfg_attr)\b|\bextern\s+crate", text) or has_path_attribute(text):
            raise ValueError("conditional compilation or external source loading is forbidden")
        sources[name] = text
    if task["id"] == "word-frequency":
        # Declaration order and whitespace are changed by ordinary cargo fmt.
        if module_declarations(sources["src/lib.rs"]) != module_declarations(task["initial"]["src/lib.rs"]):
            raise ValueError("word-frequency public module layout changed")
    return sources


def has_path_attribute(source):
    def trivia(cursor):
        while cursor < len(source):
            if source[cursor].isspace():
                cursor += 1
            elif source.startswith("//", cursor):
                end = source.find("\n", cursor)
                cursor = len(source) if end < 0 else end
            elif source.startswith("/*", cursor):
                cursor += 2
                depth = 1
                while depth and cursor < len(source):
                    if source.startswith("/*", cursor):
                        depth += 1
                        cursor += 2
                    elif source.startswith("*/", cursor):
                        depth -= 1
                        cursor += 2
                    else:
                        cursor += 1
            else:
                break
        return cursor

    cursor = 0
    name = re.compile(r"(?:r#)?path\b")
    while cursor < len(source):
        if source[cursor] != "#":
            cursor += 1
            continue
        cursor = trivia(cursor + 1)
        if source[cursor:cursor + 1] == "!":
            cursor = trivia(cursor + 1)
        if source[cursor:cursor + 1] == "[":
            cursor = trivia(cursor + 1)
            if name.match(source, cursor):
                return True
    return False


def clean_environment():
    # Build commands use explicit paths; ambient compiler/Cargo overrides cannot
    # change which sources or oracle flags get compiled.
    keep = {name: os.environ[name] for name in ["PATH", "HOME", "RUSTUP_HOME", "CARGO_HOME", "LANG"] if name in os.environ}
    keep["CARGO_NET_OFFLINE"] = "true"
    return keep


MAXIMUM_ORACLE_OUTPUT_BYTES = 1024 * 1024
MAXIMUM_AGENT_OUTPUT_BYTES = 2 * 64 * 1024 * 1024


def run_oracle_process(command, env, timeout_seconds, *, cwd=None, input_bytes=b"", maximum_output_bytes=MAXIMUM_ORACLE_OUTPUT_BYTES):
    """Bound process lifetime and pipe materialization before decoding outputs."""
    if timeout_seconds <= 0:
        return {"exit_code": None, "timed_out": True, "stdout": "", "stderr": ""}
    try:
        process = subprocess.Popen(command, env=env, cwd=cwd, stdin=subprocess.PIPE,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE, start_new_session=True)
    except OSError as error:
        return {"exit_code": None, "timed_out": False, "stdout": "", "stderr": "", "launch_error": str(error)}
    deadline = time.monotonic() + timeout_seconds
    buffers = {"stdout": bytearray(), "stderr": bytearray()}
    timed_out = output_limit = False
    input_offset = 0
    with selectors.DefaultSelector() as selector:
        for name in buffers:
            pipe = getattr(process, name)
            os.set_blocking(pipe.fileno(), False)
            selector.register(pipe, selectors.EVENT_READ, name)
        if input_bytes:
            os.set_blocking(process.stdin.fileno(), False)
            selector.register(process.stdin, selectors.EVENT_WRITE, "stdin")
        else:
            process.stdin.close()
        while selector.get_map() and not output_limit:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                timed_out = True
                break
            for key, _ in selector.select(remaining):
                pipe, name = key.fileobj, key.data
                try:
                    if name == "stdin":
                        input_offset += os.write(pipe.fileno(), input_bytes[input_offset:input_offset + 4096])
                        if input_offset == len(input_bytes):
                            selector.unregister(pipe)
                            pipe.close()
                    else:
                        chunk = os.read(pipe.fileno(), 65536)
                        if not chunk:
                            selector.unregister(pipe)
                            pipe.close()
                        else:
                            available = maximum_output_bytes - len(buffers[name])
                            buffers[name].extend(chunk[:available])
                            if len(chunk) > available:
                                output_limit = True
                                break
                except BlockingIOError:
                    continue
                except BrokenPipeError:
                    selector.unregister(pipe)
                    pipe.close()
        if not timed_out and not output_limit:
            # Observe exit without reaping: even an exited leader pins its PID/PGID
            # until the group has been signalled, preventing a reuse race.
            while os.waitid(os.P_PID, process.pid, os.WEXITED | os.WNOHANG | os.WNOWAIT) is None:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    timed_out = True
                    break
                time.sleep(min(0.01, remaining))
        # Also settle descendants that closed the streams before their parent exited.
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        for pipe in [process.stdin, process.stdout, process.stderr]:
            pipe.close()
    cleanup_pending = False
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        # Kernel-level uninterruptible I/O cannot justify an unbounded report wait.
        cleanup_pending = True
        threading.Thread(target=process.wait, daemon=True, name="rsi-oracle-reaper").start()
    return {"exit_code": process.returncode, "process_id": process.pid, "timed_out": timed_out,
            "output_limit_exceeded": output_limit, "cleanup_pending": cleanup_pending,
            **{name: data.decode(errors="replace") for name, data in buffers.items()}}


def oracle_cases(task_id, stage):
    """Only the trusted parent computes expectations and decides pass/fail."""
    cases = []
    if task_id == "utf8-truncate":
        for text in ["", "plain", "中文abc", "a😀b", "e\u0301x", "नमस्ते"]:
            data = text.encode()
            for limit in [*range(len(data) + 3), (1 << (8 * struct.calcsize("P"))) - 1]:
                prefix = data[:limit].decode(errors="ignore").encode().hex()
                cases.append((f"t {limit} {data.hex()}", f"t {prefix}"))
    elif task_id == "word-frequency":
        def words(text):
            return [word.lower() for word in re.findall(r"[A-Za-z0-9]+", text)]
        for text in ["Hi,HI! abc123_Éx 42中文42", "---中文"]:
            cases.append((f"w {text.encode().hex()}", "w " + ",".join(word.encode().hex() for word in words(text))))
        for text in ["B a A b c C a", "", *[f"{'Zoo!' * n} {'ANT_' * n} {'x ' * (n + 1)}" for n in range(1, 20)]]:
            counts = collections.Counter(words(text))
            ordered = sorted(counts.items(), key=lambda row: (-row[1], row[0]))
            cases.append((f"f {text.encode().hex()}", "f " + ",".join(f"{word.encode().hex()}:{count}" for word, count in ordered)))
    else:
        assert task_id == "interval-resume" and stage in [0, 1]
        rows = [
            ([(8, 9), (1, 4), (2, 3), (4, 5), (9, 10), (7, 6)], [(1, 5), (8, 10)]),
            ([], []), ([(1, 2), (3, 4)], [(1, 2), (3, 4)]),
            ([(2147483647, 2147483647), (-2147483648, -2147483648), (2147483646, 2147483647)], [(-2147483648, -2147483648), (2147483646, 2147483647)]),
        ] if stage == 0 else [
            ([(5, 6), (1, 2), (3, 4), (7, 9), (20, 19)], [(1, 9)]),
            ([(-3, -2), (-1, 0), (2, 4)], [(-3, 0), (2, 4)]), ([], []),
            ([(2147483647, 2147483647), (2147483646, 2147483646), (-2147483648, -2147483648)], [(-2147483648, -2147483648), (2147483646, 2147483647)]),
        ]
        for source, expected in rows:
            encode = lambda rows: ",".join(f"{a}:{b}" for a, b in rows)
            cases.append(("m " + encode(source), "m " + encode(expected)))
    return cases


